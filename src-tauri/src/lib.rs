#[cfg(debug_assertions)]
fn export_bindings() {
    // Written under target/, then copied over only if it changed: every launch of a debug exe
    // runs this (a second launch too, before it hands over to the first), and rewriting
    // bindings.ts makes Vite reload the editor, losing what it shows.
    let dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let path = dir.join("../src/shared/bindings.ts");
    let fresh = dir.join("target/bindings.ts.new");
    specta_builder()
        .export(
            specta_typescript::Typescript::default().header(
                "// @ts-nocheck\n// Generated by tauri-specta from src-tauri. Do not edit.\n",
            ),
            &fresh,
        )
        .expect("failed to export TS bindings");
    let new = std::fs::read(&fresh).expect("read the new TS bindings");
    if std::fs::read(&path).ok().as_deref() != Some(new.as_slice()) {
        std::fs::write(&path, new).expect("write the TS bindings");
    }
    let _ = std::fs::remove_file(&fresh);
}

/// User-facing app name (`productName`), e.g. "Razorcat" or, for dev builds, "Razorcat Dev".
pub(crate) fn product_name(app: &AppHandle) -> String {
    app.config()
        .product_name
        .clone()
        .unwrap_or_else(|| app.package_info().name.clone())
}

/// Opens the files a launch was given, in order (offered, if the timeline has files).
fn open_from_args(app: &AppHandle, args: &[String], cwd: &Path) {
    let checking = check::requested(args);
    let files = cli::file_paths(args, cwd);
    // A check replaces the timeline without asking.
    if checking {
        editor::request_open_all(app, files, false);
    } else {
        editor::offer(app, files);
    }
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let context = tauri::generate_context!();
    log::init(&context.config().identifier);

    #[cfg(debug_assertions)]
    export_bindings();

    let specta = specta_builder();

    tauri::Builder::default()
        // Must be the first plugin. A second launch acts in the first: it brings the editor to
        // the front and opens its file there.
        .plugin(tauri_plugin_single_instance::init(|app, args, cwd| {
            editor::focus(app);
            open_from_args(app, &args, Path::new(&cwd));
        }))
        .plugin(tauri_plugin_store::Builder::new().build())
        .plugin(tauri_plugin_dialog::init())
        .register_asynchronous_uri_scheme_protocol(protocol::SCHEME, protocol::handle)
        .invoke_handler(specta.invoke_handler())
        .setup(move |app| {
            log::open(&product_name(app.handle()));
            specta.mount_events(app);
            app.manage(AppState::new(settings::load(app.handle())));
            appearance::watch_windows_accent(app.handle());
            proxy::sweep(app.handle());
            export::probe(app.handle());
            editor::open(app.handle())?;
            let args: Vec<String> = std::env::args().collect();
            let cwd = std::env::current_dir().unwrap_or_default();
            open_from_args(app.handle(), &args, &cwd);
            logln!("[startup] ready");
            crash::test_from_env(app.handle());
            Ok(())
        })
        // The editor: files dropped on it open there (the timeline shows where, as they're
        // dragged over it), and its place on screen is remembered.
        .on_window_event(|window, event| {
            if window.label() != editor::LABEL {
                return;
            }
            let app = window.app_handle();
            match event {
                tauri::WindowEvent::DragDrop(drag) => {
                    let scale = window.scale_factor().unwrap_or(1.0);
                    let hover = |position: &tauri::PhysicalPosition<f64>| {
                        let at = position.to_logical::<f64>(scale);
                        editor::drop_hover(app, Some((at.x, at.y)));
                    };
                    match drag {
                        tauri::DragDropEvent::Enter { position, .. }
                        | tauri::DragDropEvent::Over { position } => hover(position),
                        tauri::DragDropEvent::Drop { paths, .. } => {
                            editor::offer(app, paths.clone())
                        }
                        tauri::DragDropEvent::Leave => editor::drop_hover(app, None),
                        _ => {}
                    }
                }
                tauri::WindowEvent::Moved(_) | tauri::WindowEvent::Resized(_) => {
                    editor::moved(app, window)
                }
                tauri::WindowEvent::CloseRequested { .. } => editor::closing(app, window),
                _ => {}
            }
        })
        .run(context)
        .expect("error while running Razorcat");
}
